require('./register-typescript.cjs');
const assert = require('node:assert/strict');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { createNewBoard } = require('../utils/canvasUtils.ts');
const { ELEMENT_COLORS, isElementColor } = require('../utils/elementColors.ts');
const { serializeProjectDocument, deserializeProjectDocument } = require('../utils/projectDocument.ts');
const { commitCanvasOperation, applyCanvasOperation } = require('../utils/operationHistory.ts');
const { createCanvasFinderModel } = require('../utils/canvasFinder.ts');
const { CanvasColorNavigator, CardColorMarker } = require('../components/CanvasColorNavigator.tsx');
const original = { id: 'image-1', type: 'image', name: '花灯', x: 100, y: 200, width: 300, height: 200, rotation: 0, href: '/test.png', mimeType: 'image/png' };
const tagged = { ...original, colorTag: 'purple' };
const board = { ...createNewBoard('测试画布'), elements: [tagged] };
const restored = deserializeProjectDocument(serializeProjectDocument([board]));
assert.equal(restored[0].elements[0].colorTag, 'purple', 'color survives project roundtrip');
const history = commitCanvasOperation([], -1, [original], [tagged]);
assert.equal(applyCanvasOperation([tagged], history.operationHistory[0], 'undo')[0].colorTag, undefined);
assert.equal(applyCanvasOperation([original], history.operationHistory[0], 'redo')[0].colorTag, 'purple');
assert.equal(createCanvasFinderModel([tagged], { query: '花灯' }).results[0].id, original.id);
assert.equal(isElementColor('invalid'), false);
assert.equal(ELEMENT_COLORS.length, 5);
const custom = { ...original, colorTag: '#12ab34' };
assert.equal(isElementColor(custom.colorTag), true);
assert.equal(isElementColor('#xyzxyz'), false);
const customBoard = { ...board, elements: [custom] };
assert.equal(deserializeProjectDocument(serializeProjectDocument([customBoard]))[0].elements[0].colorTag, '#12ab34');
const customNav = renderToStaticMarkup(React.createElement(CanvasColorNavigator, { elements: [custom], onFocus() {} }));
assert.match(customNav, /自定义 #12ab34标记/);
const nav = renderToStaticMarkup(React.createElement(CanvasColorNavigator, { elements: [tagged], onFocus() {} }));
assert.match(nav, /紫色标记/);
assert.match(nav, /搜索画布卡片/);
assert.doesNotMatch(nav, /黄色标记/, 'only used colors appear in the toolbar');
const marker = renderToStaticMarkup(React.createElement(CardColorMarker, { colorTag: 'purple', onChange() {} }));
assert.match(marker, /颜色标记：紫色/);
console.log('PASS canvas colors persist, undo/redo, search and toolbar render');
