require('./register-typescript.cjs');
const assert=require('node:assert/strict');
const {drawingPathData,drawingArrowHead,drawingDash,eraseDrawingPoints,stabilizeDrawingPoint}=require('../utils/drawingGeometry.ts');
assert.equal(stabilizeDrawingPoint({x:0,y:0},{x:1,y:0},1),null,'tiny hand tremor is suppressed');
const filtered=stabilizeDrawingPoint({x:0,y:0},{x:10,y:4},1);
assert.ok(filtered.x>0&&filtered.x<10&&filtered.y<4,'pen follows movement with damped jitter');
const scaled=stabilizeDrawingPoint({x:0,y:0},{x:20,y:8},0.5);
assert.ok(Math.abs(scaled.x-filtered.x*2)<1e-8,'stabilization uses screen pixels at every zoom');
const {getElementBounds}=require('../utils/canvasUtils.ts');
const {serializeProjectDocument,deserializeProjectDocument}=require('../utils/projectDocument.ts');
const path={id:'stroke',type:'path',x:0,y:0,points:[{x:0,y:0},{x:50,y:40},{x:100,y:0}],strokeColor:'#c78e28',strokeWidth:6,smooth:true,penStyle:'arrow',opacity:0.8};
assert.match(drawingPathData(path),/ Q /,'freehand drawing is a curve, not a raw polyline');
assert.equal(drawingArrowHead(path).length,3);
const head=drawingArrowHead(path);assert.deepEqual(head[1],path.points.at(-1));
const bounds=getElementBounds(path);
for(const point of [...path.points,...head])assert.ok(point.x>=bounds.x&&point.x<=bounds.x+bounds.width&&point.y>=bounds.y&&point.y<=bounds.y+bounds.height,'bounds include arrowhead and stroke');
assert.equal(drawingDash({...path,penStyle:'dotted'}),'0 15');
assert.match(drawingPathData({...path,points:[{x:5,y:5}]}),/l 0.001 0/,'a pen tap creates a round dot');
const sparse=[{x:0,y:0},{x:100,y:0}];
const untouched=eraseDrawingPoints(sparse,{x:50,y:30},{x:50,y:60},5);
assert.equal(untouched[0],sparse,'no intersection retains original geometry');
const split=eraseDrawingPoints(sparse,{x:50,y:-30},{x:50,y:30},5);
assert.equal(split.length,2,'fast eraser sweep cuts a sparse long segment');
assert.ok(Math.abs(split[0].at(-1).x-45)<1e-8);assert.ok(Math.abs(split[1][0].x-55)<1e-8);
assert.deepEqual(eraseDrawingPoints(sparse,{x:-10,y:0},{x:110,y:0},5),[],'a sweep can remove the whole stroke');
const dot=[{x:5,y:5}];
assert.deepEqual(eraseDrawingPoints(dot,{x:0,y:5},{x:10,y:5},2),[]);
assert.equal(eraseDrawingPoints(dot,{x:0,y:20},{x:10,y:20},2)[0],dot);
const tangent=eraseDrawingPoints(sparse,{x:50,y:5},{x:50,y:5},5);
assert.equal(tangent[0],sparse,'a tangential touch does not corrupt a stroke');
const legacy={...path,smooth:undefined,penStyle:undefined};assert.ok(!drawingPathData(legacy).includes(' Q '),'legacy paths retain their original shape');
const board={id:'board',name:'Drawing',elements:[path],panOffset:{x:0,y:0},zoom:1,canvasBackgroundColor:'#222'};
const document=serializeProjectDocument([board]);
const restored=deserializeProjectDocument(document);
const restoredBoards=Array.isArray(restored)?restored:restored.boards;
assert.equal(restoredBoards[0].elements[0].penStyle,'arrow');
assert.equal(restoredBoards[0].elements[0].smooth,true,'drawing appearance survives project save/load');
console.log('Drawing geometry, eraser and project round-trip checks passed.');
